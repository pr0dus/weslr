"""Internal Reasoning Graph Reasoning Engine

v94b Phase B — Reasoning Queries

Reasoning Engine:
  - Reasoning Entry Point: Operator-facing API for reasoning queries
  - Proposal Generation: Generate proposals based on gap detection (requires operator review)
  - Governance Validation: Ensure no silent autonomous mutation
  - Result Serialization: JSON export for operator review

Constraints:
  - Must NOT support silent autonomous mutation
  - Must require operator review for all proposals
  - No backend/service/UI binding
  - No scheduler/task engine
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Tuple

from .models import Node, Edge, Evidence, NodeFactory, EdgeFactory, GovernanceStatus, ProposalStatus
from .store import InternalReasoningGraphStore
from .query import InternalReasoningGraphQuery, GapReport, GovernanceBlock, ImpactAnalysis


# ============================================================================
# PROPOSAL GENERATION RESULTS
# ============================================================================


@dataclass
class ProposalCandidate:
    """Candidate proposal generated by reasoning engine."""
    proposal_id: str
    proposal_name: str
    proposal_description: str
    proposal_type: str  # "architectural", "capability", "dependency", "policy"
    confidence: float = 0.5
    required_governance: str = "operator_review"  # Only supported value
    evidence: List[Evidence] = field(default_factory=list)
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "proposal_id": self.proposal_id,
            "proposal_name": self.proposal_name,
            "proposal_description": self.proposal_description,
            "proposal_type": self.proposal_type,
            "confidence": self.confidence,
            "required_governance": self.required_governance,
            "evidence": [e.to_dict() for e in self.evidence],
        }


@dataclass
class ReasoningResult:
    """Result of reasoning operation."""
    result_id: str
    result_type: str  # "proposal_candidate", "gap_report", "impact_analysis", "governance_block"
    content: Dict[str, Any]
    confidence: float = 0.0
    governance_required: bool = True  # Always true for v94b Phase B
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "result_id": self.result_id,
            "result_type": self.result_type,
            "content": self.content,
            "confidence": self.confidence,
            "governance_required": self.governance_required,
        }


# ============================================================================
# REASONING ENGINE
# ============================================================================


class ReasoningEngine:
    """Reasoning engine for internal reasoning graph.
    
    Provides operator-facing reasoning API with governance-safe proposal generation.
    All proposals require operator review — no silent autonomous mutation.
    """
    
    def __init__(self, store: InternalReasoningGraphStore):
        """Initialize reasoning engine with store."""
        self.store = store
        self.query = InternalReasoningGraphQuery(store)
        self._result_counter = 0
    
    def _next_result_id(self) -> str:
        """Generate unique result ID."""
        self._result_counter += 1
        return f"reason_{self._result_counter}_{int(time.time())}"
    
    # --------------------------------------------------------------------------
    # PROPOSAL GENERATION
    # --------------------------------------------------------------------------
    
    def generate_proposals_from_gaps(self) -> List[ProposalCandidate]:
        """Generate candidate proposals from detected architecture gaps.
        
        This is CONSERVATIVE:
        - Only produces structured candidate proposal outputs
        - Does NOT silently commit accepted architecture truth
        - Does NOT create hidden mutation paths
        - All proposals require operator review
        """
        gaps = self.query.detect_architecture_gaps()
        proposals = []
        
        for gap in gaps:
            if gap.confidence >= 0.6:  # Only generate proposals for confident gaps
                proposal = ProposalCandidate(
                    proposal_id=f"prop_{gap.gap_id}",
                    proposal_name=gap.suggested_proposals[0]["proposal_name"],
                    proposal_description=gap.suggested_proposals[0]["proposal_description"],
                    proposal_type=gap.gap_type,
                    confidence=gap.confidence,
                    required_governance="operator_review",
                )
                proposals.append(proposal)
        
        return proposals
    
    def generate_proposal_from_impact(self, impact: ImpactAnalysis) -> Optional[ProposalCandidate]:
        """Generate proposal candidate from impact analysis.
        
        This is CONSERVATIVE:
        - Only produces structured candidate proposal outputs
        - Does NOT silently commit accepted architecture truth
        - Does NOT create hidden mutation paths
        - All proposals require operator review
        """
        if impact.confidence < 0.7:
            return None
        
        proposal = ProposalCandidate(
            proposal_id=f"prop_impact_{impact.affected_node_id}",
            proposal_name=f"Address impact on {impact.affected_name}",
            proposal_description=f"Proposed change to address {impact.impact_type} impact on {impact.affected_name}",
            proposal_type="architectural",
            confidence=impact.confidence,
            required_governance="operator_review",
        )
        
        return proposal
    
    # --------------------------------------------------------------------------
    # GOVERNANCE VALIDATION
    # --------------------------------------------------------------------------
    
    def validate_proposal_governance(self, proposal: ProposalCandidate) -> Tuple[bool, str]:
        """Validate that proposal follows governance requirements.
        
        This ensures no silent autonomous mutation:
        - Required governance must be "operator_review" (Phase B constraint)
        - Confidence must meet minimum threshold
        - Proposal must have evidence or justification
        """
        # Check required governance
        if proposal.required_governance != "operator_review":
            return False, "Proposal must require 'operator_review' governance"
        
        # Check confidence threshold
        if proposal.confidence < 0.5:
            return False, "Proposal confidence must be >= 0.5"
        
        # Check evidence/justification
        if not proposal.evidence and not proposal.proposal_description:
            return False, "Proposal must have evidence or justification"
        
        return True, "Valid governance proposal"
    
    # --------------------------------------------------------------------------
    # REASONING OPERATIONS
    # --------------------------------------------------------------------------
    
    def run_reasoning_operation(self, operation_type: str, **kwargs) -> List[ReasoningResult]:
        """Run a reasoning operation and return results.
        
        This is CONSERVATIVE:
        - All operations are read-only or proposal-generating only
        - No silent mutation of architecture
        - No autonomous execution of proposals
        - All results require operator review
        """
        results = []
        
        if operation_type == "detect_gaps":
            gaps = self.query.detect_architecture_gaps()
            for gap in gaps:
                if gap.confidence >= 0.5:
                    results.append(ReasoningResult(
                        result_id=self._next_result_id(),
                        result_type="gap_report",
                        content=gap.to_dict(),
                        confidence=gap.confidence,
                        governance_required=True,
                    ))
        
        elif operation_type == "trace_bottlenecks":
            node_id = kwargs.get("node_id")
            if node_id:
                trace = self.query.trace_bottlenecks(node_id)
                if trace:
                    results.append(ReasoningResult(
                        result_id=self._next_result_id(),
                        result_type="bottleneck_trace",
                        content=trace.to_dict(),
                        confidence=trace.confidence,
                        governance_required=False,
                    ))
        
        elif operation_type == "analyze_impact":
            node_id = kwargs.get("node_id")
            if node_id:
                impacts = self.query.analyze_dependency_impact(node_id)
                for impact in impacts:
                    results.append(ReasoningResult(
                        result_id=self._next_result_id(),
                        result_type="impact_analysis",
                        content=impact.to_dict(),
                        confidence=impact.confidence,
                        governance_required=False,
                    ))
        
        elif operation_type == "get_governance_blocks":
            blocks = self.query.get_all_governance_blocked()
            for block in blocks:
                results.append(ReasoningResult(
                    result_id=self._next_result_id(),
                    result_type="governance_block",
                    content=block.to_dict(),
                    confidence=1.0 if block.blocked_status == GovernanceStatus.REJECTED.value else 0.8,
                    governance_required=True,
                ))
        
        elif operation_type == "generate_proposals":
            proposals = self.generate_proposals_from_gaps()
            for proposal in proposals:
                results.append(ReasoningResult(
                    result_id=self._next_result_id(),
                    result_type="proposal_candidate",
                    content=proposal.to_dict(),
                    confidence=proposal.confidence,
                    governance_required=True,
                ))
        
        return results
    
    # --------------------------------------------------------------------------
    # EXPORT METHODS
    # --------------------------------------------------------------------------
    
    def export_reasoning_results(self, results: List[ReasoningResult]) -> Dict[str, Any]:
        """Export reasoning results for operator review.
        
        This is read-only export only — no mutation.
        """
        return {
            "reasoning_results": [r.to_dict() for r in results],
            "total_count": len(results),
            "governance_required_count": sum(1 for r in results if r.governance_required),
        }
    
    def export_proposal_candidates(self, proposals: List[ProposalCandidate]) -> Dict[str, Any]:
        """Export proposal candidates for operator review.
        
        This is read-only export only — no mutation.
        """
        return {
            "proposal_candidates": [p.to_dict() for p in proposals],
            "total_count": len(proposals),
            "requires_governance": True,
        }


# ============================================================================
