# ---------------------------------------------------------------------------
# 1. Search insight from timeline
# ---------------------------------------------------------------------------

def build_search_insight_proposal_from_timeline(
    user_id: str = "arthur",
    base_dir: str = ".weslr/timelines",
    path: Optional[str | pathlib.Path] = None,
    dry_run: bool = True,
) -> Dict[str, Any]:
    """Generate a search_insight proposal from the user's recent timeline.

    Reads recent session summaries via user_timeline_memory, classifies
    the dominant theme using proactive_suggestions.classify_timeline_theme,
    and builds a search_insight proposal if a relevant theme is found.

    Args:
        user_id: Which user timeline to read
        base_dir: Timeline base directory
        path: experiment_proposals.jsonl path. None = default.
        dry_run: If True, return proposal dict without writing.
                If False, append to store via append_if_new.

    Returns:
        dict with keys:
            proposal: the proposal dict (or None if no proposal)
            status: "no_proposal" | "appended" | "skipped_duplicate" | "dry_run"
            path: path to store
            proposal_id: proposal ID or None
    """
    # Import here to avoid circular import; both are read-only
    from weslr.user_timeline_memory import load_recent_session_summaries
    from weslr.proactive_suggestions import classify_timeline_theme

    summaries = load_recent_session_summaries(user_id, limit=5, base_dir=base_dir)

    if not summaries:
        return {
            "proposal": None,
            "status": "no_proposal",
            "path": str(path) if path else "weslr/experiment_proposals.jsonl",
            "proposal_id": None,
            "reason": "no timeline summaries found",
        }

    # Classify each summary, find highest-confidence theme
    theme_scores: Dict[str, float] = {}
    for event in summaries:
        result = classify_timeline_theme(event.get("summary", ""))
        theme = result["theme"]
        if theme == "unknown":
            continue
        conf = result["confidence"]
        if theme not in theme_scores or conf > theme_scores[theme]:
            theme_scores[theme] = conf

    if not theme_scores:
        return {
            "proposal": None,
            "status": "no_proposal",
            "path": str(path) if path else "weslr/experiment_proposals.jsonl",
            "proposal_id": None,
            "reason": "no strong theme detected in recent summaries",
        }

    # Pick the best theme
    best_theme = max(theme_scores, key=lambda t: theme_scores[t])
    theme_conf = theme_scores[best_theme]

    # Map to proposal template
    if best_theme not in _THEME_PROPOSAL_MAP:
        return {
            "proposal": None,
            "status": "no_proposal",
            "path": str(path) if path else "weslr/experiment_proposals.jsonl",
            "proposal_id": None,
            "reason": f"theme '{best_theme}' has no proposal template",
        }

    template = _THEME_PROPOSAL_MAP[best_theme]

    # Load existing proposals for ID counter
    store_path = path or "weslr/experiment_proposals.jsonl"
    existing = load_experiment_proposals(path=store_path)

    # Build timeline_id
    timeline_id = f"tl_{user_id}_{summaries[0].get('timestamp', 'unknown')[:10]}"

    # Determine confidence based on theme confidence
    confidence = min(0.5 + theme_conf * 0.4, 0.95)
    confidence_reasons = [
        f"theme '{best_theme}' detected in recent timeline summaries",
        f"theme confidence: {theme_conf}",
        "search_insight proposals are low risk and always operator-approval-required",
    ]

    proposal = build_experiment_proposal(
        type="search_insight",
        title=template["title"],
        description=template["description"],
        params={
            "theme": best_theme,
            "user_id": user_id,
            "summary_count": len(summaries),
        },
        confidence=round(confidence, 3),
        confidence_reasons=confidence_reasons,
        source="user_timeline",
        source_refs=[
            f"user_timeline:{user_id}",
            f"theme:{best_theme}",
        ],
        timeline_id=timeline_id,
        related_capability=template["related_capability"],
        risk_level="low",
        requires_operator_approval=True,
        existing_records=existing,
    )

    if dry_run:
        return {
            "proposal": proposal,
            "status": "dry_run",
            "path": str(store_path),
            "proposal_id": proposal["proposal_id"],
        }

    result = append_if_new(proposal, path=store_path)
    return {
        "proposal": proposal,
        "status": result["status"],
        "path": result["path"],
        "proposal_id": proposal["proposal_id"],
    }


# ---------------------------------------------------------------------------
# 2. Self-improvement proposal from SI rule
# ---------------------------------------------------------------------------

def build_self_improvement_proposal(
    rule_id: str,
    evidence: Optional[Dict[str, Any]] = None,
    path: Optional[str | pathlib.Path] = None,
    dry_run: bool = True,
) -> Dict[str, Any]:
    """Generate a self_improvement_suggestion proposal from an SI rule.

    Args:
        rule_id: SI-1 through SI-6
        evidence: Optional evidence dict with additional context
        path: experiment_proposals.jsonl path. None = default.
        dry_run: If True, return proposal dict without writing.
                If False, append to store.

    Returns:
        dict with keys: proposal, status, path, proposal_id
    """
    if rule_id not in VALID_SI_RULES:
        return {
            "proposal": None,
            "status": "invalid_rule_id",
            "path": str(path) if path else "weslr/experiment_proposals.jsonl",
            "proposal_id": None,
            "errors": [f"rule_id must be one of: {', '.join(sorted(VALID_SI_RULES))}"],
        }

    definition = _SI_DEFINITIONS[rule_id]

    store_path = path or "weslr/experiment_proposals.jsonl"
    existing = load_experiment_proposals(path=store_path)

    # Enrich params with evidence if provided
    params = dict(definition["params_template"])
    if evidence:
        params["evidence_summary"] = {
            k: v for k, v in (evidence or {}).items()
            if k in ("occurrence_count", "pattern_type", "contract", "stable_across_checks")
        }

    # Build title with type substitution for SI-2
    title = definition["title"]
    if rule_id == "SI-2" and evidence:
        exp_type = evidence.get("experiment_type", "unknown")
        title = title.replace("{type}", exp_type)

    proposal = build_experiment_proposal(
        type="self_improvement_suggestion",
        title=title,
        description=definition["description"],
        params=params,
        confidence=0.85,
        confidence_reasons=definition["confidence_reasons"],
        source="contract_insufficiency",
        source_refs=[f"si_rule:{rule_id}"],
        timeline_id=None,
        related_capability="experiments.plan",
        risk_level="low",
        requires_operator_approval=True,
        existing_records=existing,
    )

    if dry_run:
        return {
            "proposal": proposal,
            "status": "dry_run",
            "path": str(store_path),
            "proposal_id": proposal["proposal_id"],
        }

    result = append_if_new(proposal, path=store_path)
    return {
        "proposal": proposal,
        "status": result["status"],
        "path": result["path"],
        "proposal_id": proposal["proposal_id"],
    }


# ---------------------------------------------------------------------------
# 3. Generate all proposals (V1)
# ---------------------------------------------------------------------------

def generate_experiment_proposals(
    user_id: str = "arthur",
    dry_run: bool = True,
    path: Optional[str | pathlib.Path] = None,
) -> Dict[str, Any]:
    """Generate experiment proposals for the current context.

    V1 generates:
      - One search_insight proposal from user timeline (if a valid theme found)

    Does NOT generate physical_action proposals in V1.

    Args:
        user_id: User timeline to read
        dry_run: If True, do not write to store
        path: experiment_proposals.jsonl path

    Returns:
        dict with keys:
            generated: list of proposal dicts
            total_count: int
            statuses: dict of status → count
    """
    result = build_search_insight_proposal_from_timeline(
        user_id=user_id,
        dry_run=dry_run,
        path=path,
    )

    generated: List[Dict[str, Any]] = []
    statuses: Dict[str, int] = {}

    if result["proposal"] is not None:
        generated.append(result["proposal"])

    status = result["status"]
    statuses[status] = statuses.get(status, 0) + 1

    return {
        "generated": generated,
        "total_count": len(generated),
        "statuses": statuses,
        "dry_run": dry_run,
    }
