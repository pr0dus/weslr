"""ARC Synthetic 3‑Step Pilot Diagnostic Runner

Consumes the 20 task packets generated by
:func:`weslr.arc_synthetic_3_step_task_schema.generate_3_step_pilot_tasks`
and produces a structured diagnostic report.  No primitives are executed,
no external calls are made, and all leakage flags are asserted to be ``False``.
"""

from __future__ import annotations

from typing import List, Dict, Any

from .arc_synthetic_3_step_task_schema import generate_3_step_pilot_tasks

# ---------------------------------------------------------------------------
# Helper utilities – pure python, no I/O or external dependencies
# ---------------------------------------------------------------------------

def _determine_result(task: Dict[str, Any]) -> str:
    """Classify a task.

    * ``failed``  – any ``expected_failure_categories`` present.
    * ``exact``   – all ``expected_trace_requirements`` are ``True``.
    * otherwise   – ``partial``.
    """
    if task.get("expected_failure_categories"):
        return "failed"
    if all(task.get("expected_trace_requirements", {}).values()):
        return "exact"
    return "partial"


def _failure_info(task: Dict[str, Any]) -> tuple[int | None, str | None]:
    """Return ``(failure_step, failure_reason)`` for a failed task.

    The pilot does not encode a concrete failing step, so we report step ``1``
    and the first listed failure category.
    """
    if not task.get("expected_failure_categories"):
        return None, None
    reason = task["expected_failure_categories"][0]
    return 1, reason


def _trace_summaries(task: Dict[str, Any]) -> Dict[str, str]:
    """Static placeholder summaries for each step.
    Since the runner is diagnostic‑only, the content is fixed strings.
    """
    return {
        "step_1": "step 1 export summary (static)",
        "step_2": "step 2 import/export summary (static)",
        "step_3": "step 3 import summary (static)",
    }


def _parameter_flow(task: Dict[str, Any]) -> tuple[Dict[str, List[str]], Dict[str, List[str]]]:
    """Return empty carried/dropped parameter mappings.
    The pilot does not provide concrete parameter lists, and the design specifies
    empty lists are acceptable.
    """
    carried = {"1-2": [], "2-3": []}
    dropped = {"1-2": [], "2-3": []}
    return carried, dropped


def run_3_step_pilot_diagnostic() -> Dict[str, Any]:
    """Execute the diagnostic‑only runner.

    Returns a dictionary matching the structure described in the design report
    ``WESLR_ARC_SYNTHETIC_3_STEP_PILOT_RUNNER_DESIGN_V1.md``.
    """
    tasks = generate_3_step_pilot_tasks()
    assert len(tasks) == 20, "Runner expects exactly 20 tasks"

    overall = {
        "exact": 0,
        "partial": 0,
        "unsupported": 0,  # never occurs in the pilot
        "failed": 0,
        "represented_candidates": len({t["family_id"] for t in tasks}),
    }

    task_reports: List[Dict[str, Any]] = []
    for task in tasks:
        # Verify leakage flags are all False as required by the lane design
        for flag, val in task["leakage_flags"].items():
            assert val is False, f"Leakage flag {flag} must be False"

        result = _determine_result(task)
        overall[result] += 1

        failure_step, failure_reason = (None, None)
        if result == "failed":
            failure_step, failure_reason = _failure_info(task)

        trace = _trace_summaries(task)
        carried, dropped = _parameter_flow(task)

        report = {
            "task_id": task["task_id"],
            "family_id": task["family_id"],
            "result": result,
            "failure_step": failure_step,
            "failure_reason": failure_reason,
            "trace_summaries": trace,
            "carried_parameters_by_edge": carried,
            "dropped_parameters_by_edge": dropped,
            "sequence_visibility_reason": "all steps visible",
            "leakage_flags": task["leakage_flags"].copy(),
        }
        task_reports.append(report)

    return {"overall_metrics": overall, "task_reports": task_reports}

