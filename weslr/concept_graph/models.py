"""Concept Graph Models

Core data structures for the concept graph:
- Concept: Node in the graph
- Link: Typed edge between concepts
- Evidence: Provenance for concepts and links
- Backlink: Derived index (computed from links)

All classes support serialization to/from dict for persistence.
"""

from __future__ import annotations

import json
import time
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional


class LinkType(Enum):
    """Types of links between concepts."""
    # Semantic
    RELATED_TO = "related_to"
    SIMILAR_TO = "similar_to"
    OPPOSES = "opposes"
    
    # Dependency
    DEPENDS_ON = "depends_on"
    EXTENDS = "extends"
    IMPLEMENTS = "implements"
    
    # Structural
    PART_OF = "part_of"
    HAS_PART = "has_part"
    CONTAINS = "contains"
    
    # Evidence
    SUPPORTED_BY = "supported_by"
    CONTRADICTED_BY = "contradicted_by"
    
    # Causal
    CAUSES = "causes"
    ENABLES = "enables"
    PREVENTS = "prevents"


class EvidenceCategory(Enum):
    """Categories of evidence provenance."""
    SOURCE_BACKED = "source-backed"  # Verified by external source
    INFERRED = "inferred"            # Deduced from existing knowledge
    MODEL_ASSERTED = "model-asserted"  # Generated by model reasoning
    CACHED = "cached"                # Reused from previous execution
    USER_PROVIDED = "user-provided"  # Explicitly provided by operator


@dataclass
class Evidence:
    """Evidence supporting a concept or link.
    
    Each evidence item tracks:
    - source_id: Where the evidence came from
    - source_type: How it was gathered (file, message, query, reasoning)
    - content: The evidence content
    - confidence: How reliable this evidence is (0.0-1.0)
    - timestamp: When evidence was gathered
    - category: EvidenceCategory classification
    - traceable: Can be traced back to original source
    """
    source_id: str
    source_type: str
    content: str
    confidence: float
    timestamp: int
    category: str  # EvidenceCategory.value
    traceable: bool = True
    
    # Optional provenance
    reason: Optional[str] = None  # Why this evidence was gathered
    source_file: Optional[str] = None  # If from file
    source_message_id: Optional[str] = None  # If from message
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "source_id": self.source_id,
            "source_type": self.source_type,
            "content": self.content,
            "confidence": self.confidence,
            "timestamp": self.timestamp,
            "category": self.category,
            "traceable": self.traceable,
            "reason": self.reason,
            "source_file": self.source_file,
            "source_message_id": self.source_message_id,
        }
    
    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> Evidence:
        return cls(
            source_id=data["source_id"],
            source_type=data["source_type"],
            content=data["content"],
            confidence=data["confidence"],
            timestamp=data["timestamp"],
            category=data["category"],
            traceable=data.get("traceable", True),
            reason=data.get("reason"),
            source_file=data.get("source_file"),
            source_message_id=data.get("source_message_id"),
        )
    
    def is_expired(self, max_age_seconds: int = 2592000) -> bool:
        """Check if evidence is expired (default: 30 days)."""
        return time.time() - self.timestamp > max_age_seconds


@dataclass
class Link:
    """A typed link from one concept to another.
    
    Links are the primary storage for edges.
    Backlinks are derived from this structure.
    """
    source_id: str
    target_id: str
    link_type: str  # LinkType.value
    confidence: float
    reason: str  # Why this link exists
    evidence: List[Evidence]
    created_at: int
    updated_at: int
    is_stale: bool = False  # Link > 7 days old
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "source_id": self.source_id,
            "target_id": self.target_id,
            "link_type": self.link_type,
            "confidence": self.confidence,
            "reason": self.reason,
            "evidence": [e.to_dict() for e in self.evidence],
            "created_at": self.created_at,
            "updated_at": self.updated_at,
            "is_stale": self.is_stale,
        }
    
    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> Link:
        return cls(
            source_id=data["source_id"],
            target_id=data["target_id"],
            link_type=data["link_type"],
            confidence=data["confidence"],
            reason=data["reason"],
            evidence=[Evidence.from_dict(e) for e in data.get("evidence", [])],
            created_at=data["created_at"],
            updated_at=data["updated_at"],
            is_stale=data.get("is_stale", False),
        )
    
    def get_backlink(self) -> Backlink:
        """Get the corresponding backlink for target concept."""
        return Backlink(
            source_id=self.source_id,
            target_id=self.target_id,
            link_type=self.link_type,
            confidence=self.confidence,
            reason=self.reason,
            created_at=self.created_at,
        )


@dataclass
class Backlink:
    """A computed incoming link reference.
    
    Backlinks are DERIVED from Link objects.
    They are NOT primary stored truth.
    
    This structure exists for querying convenience,
    not for persistence.
    """
    source_id: str  # The concept that links TO this one
    target_id: str  # This concept
    link_type: str  # Type of link
    confidence: float  # Link confidence
    reason: str  # Why link exists
    created_at: int  # When link was created
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "source_id": self.source_id,
            "target_id": self.target_id,
            "link_type": self.link_type,
            "confidence": self.confidence,
            "reason": self.reason,
            "created_at": self.created_at,
        }


@dataclass
class Concept:
    """Represents a concept or entity in the graph.
    
    Concepts can be:
    - Permanent (is_temporary=False)
    - Temporary/session-only (is_temporary=True)
    
    Ghost concepts: is_temporary=True, promoted to permanent later.
    """
    id: str
    name: str
    type: str  # "concept" or "entity"
    description: str = ""
    aliases: List[str] = field(default_factory=list)
    tags: List[str] = field(default_factory=list)
    confidence: float = 0.5
    created_at: int = field(default_factory=lambda: int(time.time()))
    last_updated: int = field(default_factory=lambda: int(time.time()))
    is_temporary: bool = False
    is_ghost: bool = False
    links: List[Link] = field(default_factory=list)  # Outgoing links
    evidence: List[Evidence] = field(default_factory=list)  # Concept evidence
    metadata: Dict[str, Any] = field(default_factory=dict)  # Extra data
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "name": self.name,
            "type": self.type,
            "description": self.description,
            "aliases": self.aliases,
            "tags": self.tags,
            "confidence": self.confidence,
            "created_at": self.created_at,
            "last_updated": self.last_updated,
            "is_temporary": self.is_temporary,
            "is_ghost": self.is_ghost,
            "links": [l.to_dict() for l in self.links],
            "evidence": [e.to_dict() for e in self.evidence],
            "metadata": self.metadata,
        }
    
    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> Concept:
        return cls(
            id=data["id"],
            name=data["name"],
            type=data["type"],
            description=data.get("description", ""),
            aliases=data.get("aliases", []),
            tags=data.get("tags", []),
            confidence=data.get("confidence", 0.5),
            created_at=data.get("created_at", int(time.time())),
            last_updated=data.get("last_updated", int(time.time())),
            is_temporary=data.get("is_temporary", False),
            is_ghost=data.get("is_ghost", False),
            links=[Link.from_dict(l) for l in data.get("links", [])],
            evidence=[Evidence.from_dict(e) for e in data.get("evidence", [])],
            metadata=data.get("metadata", {}),
        )
    
    def get_backlinks(self) -> List[Backlink]:
        """Get backlinks derived from this concept's outgoing links."""
        return [l.get_backlink() for l in self.links]
    
    def add_evidence(self, evidence: Evidence) -> None:
        """Add evidence to this concept."""
        self.evidence.append(evidence)
        self.last_updated = int(time.time())
        # Update confidence based on evidence confidence
        self.confidence = min(1.0, self.confidence * 0.8 + evidence.confidence * 0.2)
    
    def add_link(self, link: Link) -> None:
        """Add an outgoing link."""
        self.links.append(link)
        self.last_updated = int(time.time())
        self.metadata["link_count"] = len(self.links)
