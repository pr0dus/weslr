"""Evidence Bridge for Concept Graph

Connects evidence-producing paths to Concept Graph nodes and links.

Evidence Sources Mapped:
  - Weather/time services (environmental evidence)
  - Source-backed evidence from file/message processing
  - Entity evidence (from entity_graph bridge)
  - Model assertions (reasoning traces)

Evidence Categories:
  - source-backed: Verified by external source
  - inferred: Deduced from existing knowledge
  - model-asserted: Generated by model reasoning
  - cached: Reused from previous execution
  - user-provided: Explicitly provided by operator
"""

from __future__ import annotations

import json
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

from ..models import Evidence


class EvidenceBridge:
    """Bridge from evidence sources to Concept Graph.
    
    All evidence is attached to concepts or links.
    Evidence is traceable to its source.
    """
    
    def __init__(self, workspace_dir: str = None):
        """Initialize evidence bridge."""
        self.workspace_dir = workspace_dir or str(
            Path(__file__).resolve().parent.parent.parent
        )
        self.evidence_cache_path = Path(self.workspace_dir) / "weslr" / "concept_graph" / "evidence_cache.json"
        self._evidence_cache: Dict[str, List[Dict[str, Any]]] = {}
    
    def _load_cache(self) -> None:
        """Load evidence cache."""
        if self.evidence_cache_path.exists():
            try:
                self._evidence_cache = json.loads(self.evidence_cache_path.read_text())
            except Exception:
                self._evidence_cache = {}
    
    def _save_cache(self) -> None:
        """Save evidence cache."""
        self.evidence_cache_path.parent.mkdir(parents=True, exist_ok=True)
        self.evidence_cache_path.write_text(json.dumps(self._evidence_cache, indent=2))
    
    def create_evidence(
        self,
        source_id: str,
        source_type: str,
        content: str,
        confidence: float,
        category: str = "source-backed",
        traceable: bool = True,
        reason: str = None,
        source_file: str = None,
        source_message_id: str = None,
    ) -> Evidence:
        """Create an Evidence object.
        
        Args:
            source_id: Source identifier (message_id, file_path, etc.)
            source_type: How evidence was gathered (message, file, query, reasoning)
            content: Evidence content
            confidence: How reliable this evidence is (0.0-1.0)
            category: EvidenceCategory classification
            traceable: Can be traced back to original source
            reason: Why this evidence was gathered
            source_file: If from file
            source_message_id: If from message
        
        Returns:
            Evidence object ready for attachment to concept/link
        """
        return Evidence(
            source_id=source_id,
            source_type=source_type,
            content=content,
            confidence=confidence,
            timestamp=int(time.time()),
            category=category,
            traceable=traceable,
            reason=reason,
            source_file=source_file,
            source_message_id=source_message_id,
        )
    
    def from_weather_source(
        self,
        location: str,
        weather_data: Dict[str, Any],
        source_id: str = None,
    ) -> Evidence:
        """Create evidence from weather/source data.
        
        Args:
            location: Location for weather
            weather_data: Weather observation data
            source_id: Optional source identifier
        
        Returns:
            Evidence object
        """
        content = json.dumps({
            "location": location,
            **weather_data,
        })
        
        return Evidence(
            source_id=source_id or f"weather-{location}-{int(time.time())}",
            source_type="weather_service",
            content=content[:500],  # Truncate long content
            confidence=0.95,  # High confidence for weather data
            timestamp=int(time.time()),
            category="source-backed",
            traceable=True,
            reason=f"Weather observation for {location}",
            source_file="weather_service.json",
        )
    
    def from_time_source(
        self,
        timestamp: int = None,
        source_id: str = None,
    ) -> Evidence:
        """Create evidence from time source.
        
        Args:
            timestamp: Time reference
            source_id: Optional source identifier
        
        Returns:
            Evidence object
        """
        ts = timestamp or int(time.time())
        
        return Evidence(
            source_id=source_id or f"time-{ts}",
            source_type="system_time",
            content=f"Timestamp: {ts}",
            confidence=1.0,  # Absolute for time
            timestamp=ts,
            category="source-backed",
            traceable=True,
            reason="System timestamp reference",
            source_file="system_time.json",
        )
    
    def from_file_source(
        self,
        file_path: str,
        content: str,
        confidence: float = 0.8,
        source_id: str = None,
    ) -> Evidence:
        """Create evidence from file content.
        
        Args:
            file_path: Path to file
            content: File content to reference
            confidence: Confidence in file source
            source_id: Optional source identifier
        
        Returns:
            Evidence object
        """
        return Evidence(
            source_id=source_id or f"file-{file_path}",
            source_type="file",
            content=content[:500],  # Truncate long content
            confidence=confidence,
            timestamp=int(time.time()),
            category="source-backed",
            traceable=True,
            reason=f"Evidence from file: {file_path}",
            source_file=file_path,
        )
    
    def from_message_source(
        self,
        message_id: str,
        content: str,
        confidence: float = 0.85,
        source_id: str = None,
    ) -> Evidence:
        """Create evidence from message content.
        
        Args:
            message_id: Message identifier
            content: Message content
            confidence: Confidence in message source
            source_id: Optional source identifier
        
        Returns:
            Evidence object
        """
        return Evidence(
            source_id=source_id or f"msg-{message_id}",
            source_type="message",
            content=content[:500],  # Truncate long content
            confidence=confidence,
            timestamp=int(time.time()),
            category="source-backed",
            traceable=True,
            reason=f"Evidence from message: {message_id}",
            source_message_id=message_id,
        )
    
    def from_model_assertion(
        self,
        model_id: str,
        content: str,
        reasoning: str = None,
        confidence: float = 0.7,
        source_id: str = None,
    ) -> Evidence:
        """Create evidence from model reasoning.
        
        Args:
            model_id: Model identifier
            content: Model assertion content
            reasoning: Reasoning trace
            confidence: Confidence in model assertion
            source_id: Optional source identifier
        
        Returns:
            Evidence object
        """
        evidence = Evidence(
            source_id=source_id or f"model-{model_id}-{int(time.time())}",
            source_type="model_reasoning",
            content=content[:500],
            confidence=confidence,
            timestamp=int(time.time()),
            category="model-asserted",
            traceable=True,
            reason=f"Model assertion: {reasoning or content[:100]}",
        )
        
        # Cache for potential reuse
        self._load_cache()
        cache_key = source_id or f"model-{model_id}"
        if cache_key not in self._evidence_cache:
            self._evidence_cache[cache_key] = []
        self._evidence_cache[cache_key].append(evidence.to_dict())
        self._save_cache()
        
        return evidence
    
    def from_cache(
        self,
        cache_key: str,
    ) -> List[Evidence]:
        """Load evidence from cache.
        
        Args:
            cache_key: Cache key (e.g., model_id, file_path)
        
        Returns:
            List of Evidence objects
        """
        self._load_cache()
        
        evidence_list = []
        for data in self._evidence_cache.get(cache_key, []):
            try:
                evidence = Evidence.from_dict(data)
                evidence_list.append(evidence)
            except Exception:
                pass
        
        return evidence_list
    
    def clear_cache(self) -> None:
        """Clear evidence cache."""
        self._evidence_cache = {}
        self._save_cache()


def create_evidence_from_weather(
    location: str,
    weather_data: Dict[str, Any],
) -> Evidence:
    """Convenience function: Create evidence from weather."""
    bridge = EvidenceBridge()
    return bridge.from_weather_source(location, weather_data)


def create_evidence_from_message(
    message_id: str,
    content: str,
) -> Evidence:
    """Convenience function: Create evidence from message."""
    bridge = EvidenceBridge()
    return bridge.from_message_source(message_id, content)
