# ============================================================================
# Update Policy Primitives
# ============================================================================

# Staleness thresholds (in seconds)
STALE_LINK_THRESHOLD = 7 * 24 * 60 * 60  # 7 days
EXPIRED_EVIDENCE_THRESHOLD = 30 * 24 * 60 * 60  # 30 days

# Confidence bounds
MIN_CONFIDENCE = 0.05
MAX_CONFIDENCE = 0.95


def check_staleness(created_at: int) -> bool:
    """Check if a link/evidence is stale."""
    return time.time() - created_at > STALE_LINK_THRESHOLD


def check_evidence_expiry(timestamp: int) -> bool:
    """Check if evidence has expired."""
    return time.time() - timestamp > EXPIRED_EVIDENCE_THRESHOLD


def calculate_new_confidence(
    current_confidence: float,
    new_confidence: float,
    update_type: str = "strengthen",
) -> float:
    """Calculate new confidence after an update.
    
    Args:
        current_confidence: Current confidence value (0.0-1.0)
        new_confidence: New evidence confidence (0.0-1.0)
        update_type: "strengthen", "weaken", or "update"
    
    Returns:
        New confidence value clamped to MIN_CONFIDENCE-MAX_CONFIDENCE
    """
    if update_type == "strengthen":
        # Weight towards the new evidence
        new_value = current_confidence * 0.7 + new_confidence * 0.3
    elif update_type == "weaken":
        # Reduce confidence, but not below MIN
        new_value = max(MIN_CONFIDENCE, current_confidence - (1 - new_confidence) * 0.2)
    else:  # update
        # Replace with new confidence
        new_value = current_confidence * 0.5 + new_confidence * 0.5
    
    return max(MIN_CONFIDENCE, min(MAX_CONFIDENCE, new_value))


def should_merge_links(link1: dict, link2: dict) -> bool:
    """Determine if two links should be merged.
    
    Links merge if:
    - Same source_id, target_id, and link_type
    - Confidence difference is small (< 0.2)
    """
    if link1.get("source_id") != link2.get("source_id"):
        return False
    if link1.get("target_id") != link2.get("target_id"):
        return False
    if link1.get("link_type") != link2.get("link_type"):
        return False
    
    conf1 = link1.get("confidence", 0.5)
    conf2 = link2.get("confidence", 0.5)
    return abs(conf1 - conf2) < 0.2


def merge_link_reasons(reason1: str, reason2: str) -> str:
    """Merge two link reasons into one.
    
    If reasons are the same, return one.
    If different, combine with separator.
    """
    if reason1 == reason2:
        return reason1
    return f"{reason1}; {reason2}"


# ============================================================================
# Contradiction Handling
# ============================================================================

def create_contradiction_link(
    source_id: str,
    target_id: str,
    reason: str,
    evidence: List[dict],
) -> dict:
    """Create a contradiction link.
    
    Contradiction links have link_type="contradicted_by"
    and use evidence to track the contradiction.
    """
    return {
        "source_id": source_id,
        "target_id": target_id,
        "link_type": "contradicted_by",
        "confidence": 0.8,  # High confidence for contradictions
        "reason": reason,
        "evidence": evidence,
        "created_at": int(time.time()),
        "updated_at": int(time.time()),
        "is_stale": False,
    }


def resolve_contradiction(
    contradiction_link: dict,
    resolution_type: str,
    new_evidence: List[dict] = None,
) -> dict:
    """Resolve a contradiction.
    
    Resolution types:
    - "reject_source": Reject the contradicted concept
    - "reject_target": Reject the contradicting concept
    - "accept_both": Accept both with lower confidence
    - "further_investigation": Mark for review
    """
    contradiction_link["updated_at"] = int(time.time())
    contradiction_link["metadata"] = contradiction_link.get("metadata", {})
    contradiction_link["metadata"]["resolution"] = resolution_type
    
    if new_evidence:
        contradiction_link["evidence"].extend(new_evidence)
    
    return contradiction_link


# ============================================================================
# Ghost Promotion Policy
# ============================================================================

def should_promote_ghost(
    ghost_confidence: float,
    ghost_age_days: int,
    has_evidence: bool,
    has_links: bool,
) -> bool:
    """Determine if a ghost concept should be promoted.
    
    Ghost promotion criteria:
    - High confidence (>= 0.8)
    - Has evidence (at least 1 item)
    - Has links (at least 1)
    - Old enough (>= 1 day)
    """
    return (
        ghost_confidence >= 0.8 and
        has_evidence and
        has_links and
        ghost_age_days >= 1
    )


def promote_ghost(
    ghost_concept: dict,
    promoted_by: str = "auto",
) -> dict:
    """Promote a ghost concept to permanent status."""
    ghost_concept["is_ghost"] = False
    ghost_concept["is_temporary"] = False
    ghost_concept["metadata"]["promoted_at"] = int(time.time())
    ghost_concept["metadata"]["promoted_by"] = promoted_by
    return ghost_concept
